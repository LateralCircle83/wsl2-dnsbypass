"""resolv.conf 的接管与回滚（本项目唯一会写系统文件的地方）。

设计取舍：
  * `/etc/resolv.conf` 在 WSL 里通常是指向 `/mnt/wsl/resolv.conf` 的**符号链接**。
    符号链接本身在 `/etc`（root 所有）里，改它要 root；目标文件属 root 且目录是
    sticky，普通用户也动不了。所以 bind/unbind 需要 sudo，这不是实现偷懒。
  * 接管时**把符号链接换成真文件**（glibc 只认内容；WSL 重启后由 WSL 自己重建）。
    回滚时按记录恢复：原来是什么形态就恢复成什么形态。
  * 一切动作先落"绑定记录"（JSON），unbind 只信记录，不做猜测。
  * `--target` 允许指向任意文件，用于无 sudo 的自测。
"""
from __future__ import annotations

import hashlib
import json
import os
import time
from dataclasses import dataclass
from pathlib import Path

from .config import Config, state_dir

RESOLV_CONF = Path("/etc/resolv.conf")
# WSL 的宿主 DNS 中继：一个解析器都探不到时就退回它（保命优先于正确）
WSL_HOST_RELAY = "10.255.255.254"
BIND_RECORD = "bind.json"
BACKUP_NAME = "resolv.conf.backup"
TARGET_BACKUP_NAME = "resolv.conf.target.backup"
SYSTEMD_STUB = "127.0.0.53"
# 我们生成的文件都带这行：用来判断"这份内容是不是我们自己写的"。
# 关键作用：绝不允许把"自己写的内容"当作"原始备份"存下来（旧版就是这么丢掉原始态的）。
MANAGED_MARK = "# 本文件由 dnsbypass 接管生成"
# WSL 自己生成 resolv.conf 时的原文（generateResolvConf=true 的默认输出）
WSL_DEFAULT_TEMPLATE = (
    "# This file was automatically generated by WSL. To stop automatic generation of this file, "
    "add the following entry to /etc/wsl.conf:\n"
    "# [network]\n"
    "# generateResolvConf = false\n"
    "nameserver {server}\n"
)


class ResolvError(RuntimeError):
    pass


def is_managed(text: str) -> bool:
    """这份 resolv.conf 内容是不是 dnsbypass 自己生成的？"""
    return MANAGED_MARK in text


def wsl_default_text(server: str = WSL_HOST_RELAY) -> str:
    return WSL_DEFAULT_TEMPLATE.format(server=server)


def content_md5(path: Path) -> str | None:
    try:
        return hashlib.md5(path.read_bytes()).hexdigest()
    except OSError:
        return None


@dataclass
class ResolvView:
    path: Path
    real_path: Path
    is_symlink: bool
    link_target: str | None
    exists: bool
    mode: int | None
    uid: int | None
    gid: int | None
    writable: bool
    nameservers: list[str]
    searches: list[str]
    has_options: bool
    stub_resolved: bool
    content: str

    def as_dict(self) -> dict:
        return {
            "path": str(self.path),
            "real_path": str(self.real_path),
            "is_symlink": self.is_symlink,
            "link_target": self.link_target,
            "exists": self.exists,
            "mode": f"0o{self.mode:o}" if self.mode is not None else None,
            "uid": self.uid,
            "gid": self.gid,
            "writable": self.writable,
            "nameservers": self.nameservers,
            "searches": self.searches,
            "stub_resolved": self.stub_resolved,
            "content": self.content,
        }


def parse_nameservers(text: str) -> list[str]:
    servers: list[str] = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) >= 2 and parts[0] == "nameserver":
            servers.append(parts[1])
    return servers


def parse_searches(text: str) -> list[str]:
    out: list[str] = []
    for line in text.splitlines():
        parts = line.split("#", 1)[0].split()
        if len(parts) >= 2 and parts[0] in {"search", "domain"}:
            out.extend(parts[1:])
    return out


def inspect(path: Path | str = RESOLV_CONF) -> ResolvView:
    target = Path(path)
    is_symlink = target.is_symlink()
    link_target = os.readlink(target) if is_symlink else None
    try:
        real = target.resolve()
    except OSError:
        real = target
    exists = target.exists()
    mode = uid = gid = None
    content = ""
    try:
        stat = target.stat()
        mode, uid, gid = stat.st_mode & 0o777, stat.st_uid, stat.st_gid
    except OSError:
        pass
    try:
        content = target.read_text(encoding="utf-8", errors="replace")
    except OSError:
        content = ""
    nameservers = parse_nameservers(content)
    return ResolvView(
        path=target,
        real_path=real,
        is_symlink=is_symlink,
        link_target=link_target,
        exists=exists,
        mode=mode,
        uid=uid,
        gid=gid,
        writable=os.access(target, os.W_OK) if exists else os.access(target.parent, os.W_OK),
        nameservers=nameservers,
        searches=parse_searches(content),
        has_options=any(l.split("#", 1)[0].strip().startswith("options") for l in content.splitlines()),
        stub_resolved=SYSTEMD_STUB in nameservers or (link_target or "").endswith("stub-resolv.conf"),
        content=content,
    )


def render(cfg: Config, host: str | None = None, fallbacks: list[str] | None = None) -> str:
    lines = [
        "# 本文件由 dnsbypass 接管生成；用 `dnsbypass unbind` 恢复原状。",
        f"# 生成时间: {time.strftime('%Y-%m-%d %H:%M:%S')}",
        f"nameserver {host or cfg['bind_host']}",
    ]
    servers = fallbacks if fallbacks is not None else (cfg.get("fallback_nameservers") or [])
    for server in servers:
        lines.append(f"nameserver {server}")
    options = (cfg.get("resolvconf_options") or "").strip()
    if options:
        lines.append(f"options {options}")
    return "\n".join(lines) + "\n"


def record_path(cfg: Config) -> Path:
    return state_dir(cfg) / BIND_RECORD


def load_record(cfg: Config) -> dict | None:
    path = record_path(cfg)
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def prepare_state_dir(cfg: Config, log=print) -> Path:
    """root 跑时把状态目录交还给调用者，避免留下 root 所有的文件。"""
    directory = state_dir(cfg)
    if os.geteuid() == 0 and os.environ.get("SUDO_UID"):
        try:
            os.chown(directory, int(os.environ["SUDO_UID"]), int(os.environ.get("SUDO_GID", "0")))
        except OSError as exc:
            log(f"[dnsbypass] 状态目录 chown 失败: {exc}")
    return directory


def detect_fallbacks(cfg: Config, host: str | None = None, view: ResolvView | None = None) -> list[str]:
    """挑出"除自己以外"的解析器当明文兜底（bind 写进 resolv.conf，引擎自己也要用）。

    必须排除自己，否则重新 bind 会把 127.0.0.2 当成兜底 → 引擎向自己发查询（自环）。
    """
    view = view or inspect()
    own = {host, cfg.get("bind_host"), cfg.get("listen_host"), "127.0.0.1", "::1", "0.0.0.0", ""}
    out = [s for s in view.nameservers if s not in own]
    if not out and WSL_HOST_RELAY not in own:
        out = [WSL_HOST_RELAY]
    return out


def bind(cfg: Config, target: Path | str = RESOLV_CONF, dry_run: bool = False, log=print) -> dict:
    path = Path(target)
    view = inspect(path)
    host = cfg["bind_host"]
    # 兜底解析器：配置里没写就自动沿用原来的（保命：引擎挂了至少还能解析）。
    fallbacks = list(cfg.get("fallback_nameservers") or [])
    if not fallbacks:
        fallbacks = detect_fallbacks(cfg, host, view)
    desired = render(cfg, host, fallbacks)

    if view.stub_resolved:
        raise ResolvError(
            f"{path} 看起来由 systemd-resolved 管理（{SYSTEMD_STUB} / stub-resolv.conf）；"
            "先处理 systemd-resolved，否则改这里不生效。"
        )
    if view.is_symlink and view.link_target and "stub-resolv.conf" in view.link_target:
        raise ResolvError(f"{path} 指向 systemd-resolved 的 stub 文件，不能直接接管。")

    managed = is_managed(view.content)
    prev = load_record(cfg)
    prev_matches = bool(prev and prev.get("target") == str(path))
    inherited = False

    # 原始身份只认"第一次"那份记录：哪怕当前文件已经是我们自己生成的真文件
    # （比如上次 unbind 没跑完、或者托管中又 bind 了一次），也必须沿用它最初的形态，
    # 否则会把"符号链接"这个事实弄丢，回滚时就再也变不回链接了。
    if managed or (prev_matches and prev.get("status") == "bound" and prev.get("original_kind") == "symlink"):
        if not prev_matches:
            raise ResolvError(
                f"{path} 的内容已经是 dnsbypass 生成的，但找不到对应的绑定记录（状态目录换过？）。\n"
                "  拒绝接管以免丢掉原始信息：先 `dnsbypass repair` 恢复 WSL 原始 resolv.conf，再重新 bind。"
            )
        original_kind = prev.get("original_kind")
        original_link_target = prev.get("original_link_target")
        original_mode = prev.get("original_mode")
        original_uid = prev.get("original_uid")
        original_gid = prev.get("original_gid")
        inherited = True
        log(f"[dnsbypass] 当前文件是上次托管的产物，沿用首次记录的原始形态（{original_kind}）")
    else:
        original_kind = "symlink" if view.is_symlink else ("file" if view.exists else "missing")
        original_link_target = view.link_target
        original_mode, original_uid, original_gid = view.mode, view.uid, view.gid

    record = {
        "version": 2,
        "created_at": time.time(),
        "created_at_text": time.strftime("%Y-%m-%d %H:%M:%S"),
        "target": str(path),
        "original_kind": original_kind,
        "original_link_target": original_link_target,
        "original_mode": original_mode,
        "original_uid": original_uid,
        "original_gid": original_gid,
        "dnsbypass_nameserver": host,
        "fallback_nameservers": fallbacks,
        "desired_content": desired,
        "dry_run": dry_run,
        "inherited_original": inherited,
        "current_was_managed": managed,
    }
    if inherited and prev_matches and prev.get("created_at"):
        # created_at 记的是"首次接管"的时间。重复 bind 不该把它刷新成现在，
        # 否则记录看起来像"刚刚才接管"，排障时会被误导。
        record["created_at"] = prev["created_at"]
        record["created_at_text"] = prev.get("created_at_text") or record["created_at_text"]
        record["rebound_at"] = time.time()
        record["rebound_at_text"] = time.strftime("%Y-%m-%d %H:%M:%S")

    if dry_run:
        record["status"] = "planned"
        log(f"[dry-run] 会把 {path} 设为:\n{desired}")
        return record

    directory = prepare_state_dir(cfg, log=log)
    backup = directory / BACKUP_NAME
    if prev_matches and prev.get("backup_path"):
        backup = Path(prev["backup_path"])
    record["backup_path"] = str(backup)

    # 备份只写一次，而且只写"不是我们自己生成"的内容 —— 旧版在这里无条件覆盖，
    # 结果第二次 bind 时把污染内容当成了"原始备份"，回滚就还原不回去了。
    if view.exists and not managed:
        if not backup.exists():
            _atomic_write(backup, view.content, mode=0o644)
            _chown_to_caller(backup)
            log(f"[dnsbypass] 已保存原始备份 {backup}")
        elif is_managed(backup.read_text(encoding="utf-8", errors="replace")):
            # 备份里是旧版留下的自产内容 → 现在手里才是真正的原始内容，替换掉它。
            # （这里以前写成 elif、条件又要求 not managed，永远走不到，导致用户
            #   `unbind` 被我们的安全检查挡住、只能 repair —— 实测踩过。）
            _atomic_write(backup, view.content, mode=0o644)
            _chown_to_caller(backup)
            log(f"[dnsbypass] 旧版留下的无效备份（内容是自产的）已被真正的原始内容替换：{backup}")
        else:
            log(f"[dnsbypass] 已有原始备份，保持不动：{backup}")

    if managed:
        healthy_backup = False
        if backup.exists():
            if is_managed(backup.read_text(encoding="utf-8", errors="replace")):
                # 托管期间发现备份是旧版留下的自产内容：链接目标还在的话，手里就有
                # 真正的原始内容，顺手治好它，免得日后 unbind 又被挡住。
                real = Path(original_link_target or "")
                text = real.read_text(encoding="utf-8", errors="replace") if str(real) and real.exists() else ""
                if text and not is_managed(text):
                    _atomic_write(backup, text, mode=0o644)
                    _chown_to_caller(backup)
                    healthy_backup = True
                    log(f"[dnsbypass] 托管中发现无效备份（内容是自产的），已用 {real} 的真实内容替换：{backup}")
                else:
                    log(f"[!] 原始备份内容是自产的，且链接目标不可用；回滚请用 `dnsbypass repair`（{backup}）")
            else:
                healthy_backup = True
        else:
            log(f"[!] 托管中重复 bind，但找不到原始备份 {backup}；回滚将依赖 {TARGET_BACKUP_NAME}")
        if healthy_backup:
            log(f"[dnsbypass] 托管中重复 bind：原始备份保持不动（{backup}）")

    try:
        if original_kind == "symlink" and original_link_target:
            # 关键：**不写**符号链接的目标文件。旧版会写穿到 /mnt/wsl/resolv.conf，
            # 把 WSL 的原始内容覆盖掉，于是回滚也无法还原它。这里只单独留一份目标备份，
            # 目标文件保持原样（glibc 只读 /etc/resolv.conf 的内容，不关心目标是什么）。
            real = Path(original_link_target)
            if real != path and real.exists():
                text = real.read_text(encoding="utf-8", errors="replace")
                target_backup = directory / TARGET_BACKUP_NAME
                if not is_managed(text):
                    if not target_backup.exists() or is_managed(
                            target_backup.read_text(encoding="utf-8", errors="replace")):
                        _atomic_write(target_backup, text, mode=0o644)
                        _chown_to_caller(target_backup)
                    record["target_backup_path"] = str(target_backup)
                    log(f"[dnsbypass] 已保存链接目标备份 {target_backup}（{real} 保持原样）")
            _replace_with_regular(path, desired, uid=view.uid, gid=view.gid, mode=0o644)
        else:
            _atomic_write(path, desired, uid=view.uid, gid=view.gid,
                          mode=(view.mode or original_mode or 0o644))
    except PermissionError as exc:
        raise ResolvError(f"写入 {path} 需要 root：{exc}") from exc
    except OSError as exc:
        raise ResolvError(f"写入 {path} 失败：{exc}") from exc

    record["status"] = "bound"
    save_record(cfg, record, log=log)
    log(f"[dnsbypass] 已接管 {path} → nameserver {host}")
    return record


def unbind(cfg: Config, dry_run: bool = False, log=print, target: Path | str | None = None) -> dict:
    record = load_record(cfg)
    if not record:
        raise ResolvError("找不到绑定记录，拒绝猜着改；如需强行恢复请用 `dnsbypass repair`。")
    path = Path(target or record["target"])
    kind = record.get("original_kind")
    backup = Path(record["backup_path"]) if record.get("backup_path") else None
    backup_text = (backup.read_text(encoding="utf-8", errors="replace")
                   if backup and backup.exists() else None)

    # 旧版缺陷的兜底：备份里若存的是我们自己写的内容，那根本不是"原始态"。
    # 但只有在**真的需要把备份内容写回去**（原形态是普通文件）时它才致命；
    # 原形态是符号链接时根本用不到备份内容（链接目标还在就足够了），
    # 不该因为一份坏备份就把能安全回滚的用户挡住 —— 实测被挡过。
    backup_is_managed = backup_text is not None and is_managed(backup_text)
    if kind == "file" and backup_is_managed:
        raise ResolvError(
            "备份文件里存的是 dnsbypass 自己生成的内容（旧版缺陷），拿它回滚没有意义。\n"
            "  请改用 `dnsbypass repair`：它会恢复 WSL 原始 resolv.conf（必要时按 WSL 默认模板重建）；\n"
            "  或者在 Windows 执行 `wsl --shutdown`，让 WSL 自己重新生成 /etc/resolv.conf 与 /mnt/wsl/resolv.conf。"
        )

    actions: list[str] = []
    if kind == "symlink":
        actions.append(f"恢复符号链接 {path} → {record.get('original_link_target')}")
        if record.get("target_backup_path"):
            actions.append(f"用备份还原链接目标 {record['original_link_target']}")
    elif kind == "file":
        actions.append(f"用 {backup} 覆盖 {path}")
    else:
        actions.append(f"删除 {path}（它原本不存在）")

    if dry_run:
        log("[dry-run] " + "；".join(actions))
        return {"status": "planned", "actions": actions, "record": record}

    if kind == "file" and backup_text is not None:
        _atomic_write(path, backup_text, uid=record.get("original_uid"),
                      gid=record.get("original_gid"), mode=record.get("original_mode") or 0o644)
    elif kind == "symlink":
        target_backup = Path(record["target_backup_path"]) if record.get("target_backup_path") else None
        real_target = Path(record.get("original_link_target") or "")
        # 新记录：只还原"链接目标"的备份；旧记录（曾写穿过目标）用它的备份还原目标文件
        if target_backup and target_backup.exists() and str(real_target):
            text = target_backup.read_text(encoding="utf-8", errors="replace")
            if not is_managed(text):
                _atomic_write(real_target, text, uid=record.get("original_uid"),
                              gid=record.get("original_gid"), mode=record.get("original_mode") or 0o644)
        elif record.get("wrote_real_path") and backup_text is not None:
            _atomic_write(Path(record["wrote_real_path"]), backup_text,
                          uid=record.get("original_uid"), gid=record.get("original_gid"),
                          mode=record.get("original_mode") or 0o644)
        # 链接目标还健康的话，顺手把"旧版坏备份"治好，免得下次 bind/unbind 又被它绊住
        if real_target and str(real_target) and real_target.exists():
            real_text = real_target.read_text(encoding="utf-8", errors="replace")
            if not is_managed(real_text) and (backup_text is None or backup_is_managed):
                backup = backup or (state_dir(cfg) / BACKUP_NAME)
                _atomic_write(backup, real_text, mode=0o644)
                _chown_to_caller(backup)
                record["backup_path"] = str(backup)
                log(f"[dnsbypass] 顺带修好了无效备份（用 {real_target} 的真实内容）：{backup}")
        if path.exists() or path.is_symlink():
            path.unlink()
        path.symlink_to(record["original_link_target"])
    elif kind == "missing":
        if path.exists() or path.is_symlink():
            path.unlink()

    record["status"] = "unbound"
    record["unbound_at"] = time.time()
    save_record(cfg, record, log=log)
    log(f"[dnsbypass] 已回滚 {path}（{kind}）")
    return {"status": "unbound", "actions": actions, "record": record}


def repair(cfg: Config, target: Path | str = RESOLV_CONF, real: Path | str | None = None,
           nameserver: str | None = None, dry_run: bool = False, log=print) -> dict:
    """把 resolv.conf 恢复成"没被我们碰过"的样子。

    用于两种情况：① unbind 的记录/备份已损坏（旧版缺陷）；② 想直接放弃托管、回到 WSL 原始态。
    恢复优先用"真·原始备份"，没有就按 WSL 的默认模板重建（`generateResolvConf = true` 时
    WSL 自己生成的就是这个内容），并把 /etc/resolv.conf 变回指向目标文件的符号链接。
    """
    path = Path(target)
    view = inspect(path)
    record = load_record(cfg) or {}
    if real:
        real_path = Path(real)
    else:
        candidate = record.get("original_link_target") or record.get("wrote_real_path") or view.link_target
        if candidate:
            real_path = Path(candidate)
        elif str(path) == str(RESOLV_CONF):
            real_path = Path("/mnt/wsl/resolv.conf")
        else:
            real_path = path.with_name(path.name + ".real")

    directory = state_dir(cfg)
    content: str | None = None
    source = ""
    backup = Path(record["backup_path"]) if record.get("backup_path") else (directory / BACKUP_NAME)
    if backup.exists():
        text = backup.read_text(encoding="utf-8", errors="replace")
        if not is_managed(text):
            content, source = text, f"原始备份 {backup}"
    server = nameserver or next((s for s in (record.get("fallback_nameservers") or []) if s), WSL_HOST_RELAY)
    if content is None:
        content, source = wsl_default_text(server), f"WSL 默认模板（nameserver {server}）"

    digest = hashlib.md5(content.encode("utf-8")).hexdigest()
    payload = {
        "status": "planned" if dry_run else "repaired",
        "target": str(path),
        "real_path": str(real_path),
        "content_source": source,
        "content_md5": digest,
        "content": content,
    }
    if dry_run:
        log(f"[dry-run] 会把 {real_path} 恢复成（来源：{source}）：\n{content}"
            f"并把 {path} 变回指向它的符号链接")
        return payload

    if not dry_run:
        prepare_state_dir(cfg, log=log)
    uid = record.get("original_uid")
    gid = record.get("original_gid")
    if uid is None and os.geteuid() == 0:
        uid = gid = 0
    _atomic_write(real_path, content, uid=uid, gid=gid, mode=record.get("original_mode") or 0o644)
    try:
        if path.exists() or path.is_symlink():
            path.unlink()
        path.symlink_to(real_path)
    except PermissionError as exc:
        raise ResolvError(
            f"恢复 {path} 的符号链接权限不足（{exc}）。\n"
            "  这一步要动 /etc 和 /mnt/wsl，必须 root：`sudo dnsbypass repair`。"
        ) from exc
    except OSError as exc:
        raise ResolvError(f"恢复 {path} 的符号链接失败：{exc}") from exc

    record.update({
        "version": max(2, int(record.get("version") or 1)),
        "status": "repaired",
        "target": str(path),
        "repaired_at": time.time(),
        "repair_source": source,
        "restored_real_path": str(real_path),
        "restored_content_md5": digest,
    })
    save_record(cfg, record, log=log)
    log(f"[dnsbypass] 已恢复 {path} → {real_path}（{source}，md5 {digest}）")
    return payload


def save_record(cfg: Config, record: dict, log=print) -> None:
    directory = prepare_state_dir(cfg, log=log)
    path = directory / BIND_RECORD
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(record, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(path)


