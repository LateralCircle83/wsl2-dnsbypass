def _chown_to_caller(path: Path) -> None:
    """root 跑时把状态文件交还给调用者（SUDO_UID/SUDO_GID），免得备份只有 root 能读。"""
    if os.geteuid() != 0:
        return
    try:
        uid = int(os.environ["SUDO_UID"])
        gid = int(os.environ.get("SUDO_GID", "0"))
    except (KeyError, ValueError):
        return
    try:
        os.chown(path, uid, gid)
    except OSError:
        pass


def _tmp_sibling(path: Path, tag: str = "tmp") -> Path:
    """在同目录里造一个**唯一**的临时文件名。

    不能固定叫 `<name>.dnsbypass.tmp`：`/mnt/wsl` 和 `/tmp` 都是 1777+sticky 的目录，
    一旦上一次以普通用户身份失败、留下同名文件，后续**连 root 都写不进去** ——
    Linux 的 `fs.protected_regular=2`（Ubuntu 默认）正是防这种"临时文件抢注"，
    它不豁免 root。实测踩过：`sudo dnsbypass repair` 直接 PermissionError。
    """
    token = os.urandom(4).hex()
    return path.with_name(f"{path.name}.dnsbypass.{os.getpid()}.{token}.{tag}")


def _remove_stale_tmp(path: Path, log=None) -> None:
    """清掉旧版本留下的固定名临时文件（清不掉就算了，不影响主流程）。"""
    for name in (path.name + ".dnsbypass.tmp", path.name + ".dnsbypass.new"):
        stale = path.with_name(name)
        if not stale.exists() and not stale.is_symlink():
            continue
        try:
            stale.unlink()
            if log:
                log(f"[dnsbypass] 清掉上次失败留下的临时文件 {stale}")
        except OSError:
            pass


def _write_tmp_and_move(tmp: Path, target: Path, content: str, uid, gid, mode: int) -> None:
    target = Path(target)
    try:
        try:
            tmp.write_text(content, encoding="utf-8")
            os.chmod(tmp, mode)
            if uid is not None and gid is not None and os.geteuid() == 0:
                os.chown(tmp, uid, gid)
            tmp.replace(target)
        except PermissionError as exc:
            raise ResolvError(
                f"写入 {target} 权限不足（{exc}）。\n"
                "  /etc/resolv.conf 与 /mnt/wsl/resolv.conf 都需要 root："
                "试试 `sudo dnsbypass repair` / `sudo dnsbypass bind`。"
            ) from exc
        except OSError as exc:
            raise ResolvError(f"写入 {target} 失败：{exc}") from exc
    finally:
        # 无论成败都不留垃圾（在 1777+sticky 目录里留垃圾会咬到下一次运行）
        if tmp.exists() or tmp.is_symlink():
            try:
                tmp.unlink()
            except OSError:
                pass


def _atomic_write(path: Path, content: str, uid=None, gid=None, mode: int = 0o644) -> None:
    path = Path(path)
    _remove_stale_tmp(path)
    _write_tmp_and_move(_tmp_sibling(path), path, content, uid, gid, mode)


def _replace_with_regular(path: Path, content: str, uid=None, gid=None, mode: int = 0o644) -> None:
    """把符号链接换成同名真文件（先写临时文件，再搬走链接，再就位）。"""
    path = Path(path)
    _remove_stale_tmp(path)
    holder = _tmp_sibling(path, tag="new")
    try:
        holder.write_text(content, encoding="utf-8")
        os.chmod(holder, mode)
        if uid is not None and gid is not None and os.geteuid() == 0:
            os.chown(holder, uid, gid)
    except PermissionError as exc:
        raise ResolvError(
            f"写入 {path} 权限不足（{exc}）。需要 root：试试 `sudo dnsbypass bind`。"
        ) from exc
    try:
        path.unlink()
    except FileNotFoundError:
        pass
    except PermissionError as exc:
        raise ResolvError(f"替换 {path} 需要 root：{exc}") from exc
    try:
        holder.replace(path)
    except OSError as exc:
        raise ResolvError(f"就位 {path} 失败：{exc}") from exc