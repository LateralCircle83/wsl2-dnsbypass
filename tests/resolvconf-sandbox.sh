#!/usr/bin/env bash
# resolv.conf 接管的沙箱回归测试 —— 不需要 root，不碰任何系统文件。
#
# 用法: tests/resolvconf-sandbox.sh
# 覆盖: bind / 托管中重复 bind / unbind / 旧版坏记录被拒绝 / repair / repair 幂等
set -u
P="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
S="$(mktemp -d /tmp/dnsbypass-rc-XXXXXX)"
FAIL=0

PRISTINE='# This file was automatically generated by WSL. To stop automatic generation of this file, add the following entry to /etc/wsl.conf:
# [network]
# generateResolvConf = false
nameserver 10.255.255.254'
PRISTINE_MD5=ccd28ae0776549eb3926db2148a50bff

mkdir -p "$S/state"
printf '%s\n' "$PRISTINE" > "$S/real.conf"
ln -s "$S/real.conf" "$S/etc.conf"
KEEP=$(md5sum "$S/real.conf" | cut -d' ' -f1)

run() { (cd "$P" && python3 -m dnsbp.cli --state-dir "$S/state" "$@" 2>&1); }
chk() { # chk <描述> <期望> <实际>
  if [ "$2" = "$3" ]; then echo "  ✅ $1"; else echo "  ❌ $1  期望[$2] 实际[$3]"; FAIL=1; fi
}

echo "== 1) 首次 bind（原始是符号链接）=="
run bind --target "$S/etc.conf" >/dev/null
chk "etc.conf 变成真文件" "regular file" "$(stat -c %F "$S/etc.conf")"
chk "含 dnsbypass 标记" "yes" "$(grep -q 'dnsbypass 接管生成' "$S/etc.conf" && echo yes || echo no)"
chk "真正的目标文件 real.conf 未被写穿" "$KEEP" "$(md5sum "$S/real.conf" | cut -d' ' -f1)"
chk "原始备份可用" "$KEEP" "$(md5sum "$S/state/resolv.conf.backup" | cut -d' ' -f1)"
chk "目标备份可用" "$KEEP" "$(md5sum "$S/state/resolv.conf.target.backup" | cut -d' ' -f1)"
chk "记录原形态=symlink" "symlink" "$(python3 -c "import json;print(json.load(open('$S/state/bind.json'))['original_kind'])")"

echo "== 2) 再 bind 一次（托管中重复 bind，旧版就是在这里丢原始态的）=="
run bind --target "$S/etc.conf" >/dev/null
chk "备份没有被自产内容覆盖" "$KEEP" "$(md5sum "$S/state/resolv.conf.backup" | cut -d' ' -f1)"
chk "记录仍记得原形态=symlink" "symlink" "$(python3 -c "import json;print(json.load(open('$S/state/bind.json'))['original_kind'])")"
chk "记录标注沿用了原始形态" "True" "$(python3 -c "import json;print(json.load(open('$S/state/bind.json'))['inherited_original'])")"

echo "== 3) unbind 回滚 =="
run unbind --target "$S/etc.conf" >/dev/null
chk "etc.conf 变回符号链接" "yes" "$([ -L "$S/etc.conf" ] && echo yes || echo no)"
chk "链接目标正确" "$S/real.conf" "$(readlink "$S/etc.conf")"
chk "读到的内容 = 原始内容" "$KEEP" "$(md5sum "$S/etc.conf" | cut -d' ' -f1)"
chk "real.conf 仍是原始内容" "$KEEP" "$(md5sum "$S/real.conf" | cut -d' ' -f1)"

echo "== 4) 模拟旧版缺陷：记录退化成 file + 备份是自产内容 =="
printf '# 本文件由 dnsbypass 接管生成；用 `dnsbypass unbind` 恢复原状。\nnameserver 127.0.0.2\nnameserver 10.255.255.254\n' > "$S/etc.conf"
SB="$S" python3 - <<'PY'
import json, os
p = os.path.join(os.environ["SB"], "state", "bind.json")
r = json.load(open(p))
r.update({"original_kind": "file", "original_link_target": None, "status": "bound",
          "target": os.path.join(os.environ["SB"], "etc.conf"),
          "backup_path": os.path.join(os.environ["SB"], "state", "resolv.conf.backup")})
json.dump(r, open(p, "w"), ensure_ascii=False, indent=2)
PY
printf '# 本文件由 dnsbypass 接管生成；用 `dnsbypass unbind` 恢复原状。\nnameserver 127.0.0.2\n' > "$S/state/resolv.conf.backup"
out=$(run unbind --target "$S/etc.conf"; echo "rc=$?")
chk "unbind 拒绝用污染备份回滚" "yes" "$(echo "$out" | grep -q '旧版缺陷' && echo yes || echo no)"
chk "unbind 退出码=40" "40" "$(echo "$out" | tail -1 | cut -d= -f2)"

echo "== 5) repair 救命（重建 WSL 原始态）=="
run repair --target "$S/etc.conf" --nameserver 10.255.255.254 >/dev/null
chk "repair 后变回符号链接" "yes" "$([ -L "$S/etc.conf" ] && echo yes || echo no)"
chk "内容 = WSL 原始原文（md5 逐字节一致）" "$PRISTINE_MD5" "$(md5sum "$S/etc.conf" | cut -d' ' -f1)"
chk "real.conf 也恢复成原文" "$PRISTINE_MD5" "$(md5sum "$S/real.conf" | cut -d' ' -f1)"
chk "记录状态=repaired" "repaired" "$(python3 -c "import json;print(json.load(open('$S/state/bind.json'))['status'])")"

echo "== 6) repair 幂等（再跑一次仍一致）=="
run repair --target "$S/etc.conf" >/dev/null
chk "再跑一次 md5 不变" "$PRISTINE_MD5" "$(md5sum "$S/etc.conf" | cut -d' ' -f1)"

echo "== 7) 坏备份自愈：bind 一见到真原始内容就替换掉自产备份 =="
run bind --target "$S/etc.conf" >/dev/null
printf '# 本文件由 dnsbypass 接管生成；用 `dnsbypass unbind` 恢复原状。\nnameserver 127.0.0.2\n' > "$S/state/resolv.conf.backup"
out=$(run bind --target "$S/etc.conf")
chk "bind 识别出坏备份并替换" "yes" "$(echo "$out" | grep -q '无效备份' && echo yes || echo no)"
chk "备份内容 = WSL 原文" "$PRISTINE_MD5" "$(md5sum "$S/state/resolv.conf.backup" | cut -d' ' -f1)"

echo "== 8) 坏备份 + 原形态是符号链接：不该把能安全回滚的人挡住 =="
printf '# 本文件由 dnsbypass 接管生成；用 `dnsbypass unbind` 恢复原状。\nnameserver 127.0.0.2\n' > "$S/state/resolv.conf.backup"
out=$(run unbind --target "$S/etc.conf"; echo "rc=$?")
chk "unbind 成功（不再拒绝）" "0" "$(echo "$out" | tail -1 | cut -d= -f2)"
chk "变回符号链接" "yes" "$([ -L "$S/etc.conf" ] && echo yes || echo no)"
chk "坏备份顺带被治好" "$PRISTINE_MD5" "$(md5sum "$S/state/resolv.conf.backup" | cut -d' ' -f1)"

echo "== 9) 旧版固定名临时文件（fs.protected_regular=2 的坑）不会再挡住写入 =="
: > "$S/etc.conf.dnsbypass.tmp"     # 模拟上次以普通用户失败后留下的垃圾
run bind --target "$S/etc.conf" >/dev/null
chk "bind 仍然成功" "yes" "$(grep -q 'dnsbypass 接管生成' "$S/etc.conf" && echo yes || echo no)"
chk "垃圾临时文件被清掉" "no" "$([ -e "$S/etc.conf.dnsbypass.tmp" ] && echo yes || echo no)"
chk "没有残留 .dnsbypass.* 文件" "0" "$(find "$S" -name '*.dnsbypass.*' | wc -l)"

rm -rf "$S"
if [ "$FAIL" = 0 ]; then echo "全部通过"; else echo "有失败项"; fi
exit "$FAIL"